import assert from 'node:assert/strict';
import {createTestFlight} from '../client/withu-renderer/src/model-config/test-flight.mjs';
const flight=createTestFlight();
const selected={provider_id:'p',model_ref:'m',kind:'llm',config_version:2};
const proof={...selected,operation_id:'op'};
let token=flight.begin(selected);
assert.equal(flight.accept({...proof,config_version:1}),null);
assert.equal(flight.accept({...proof,model_ref:'old'}),null);
assert.equal(flight.accept({...proof,operation_id:'previous'}),null);
assert.equal(flight.accept(proof),null,'early proof must wait for authoritative operation ID');
assert.deepEqual(flight.settle(token,proof),{running:false,proof},'event before promise must not resurrect running state');
assert.equal(flight.accept(proof),null,'duplicate terminal event ignored');
token=flight.begin(selected);
assert.deepEqual(flight.settle(token,proof),{running:true,proof:null});
assert.equal(flight.accept({...proof,operation_id:'unrelated'}),null);
assert.equal(flight.accept(proof),proof);
const old=flight.begin(selected);flight.begin({...selected,model_ref:'new'});
assert.equal(flight.settle(old,proof),null);
assert.equal(flight.accept(proof),null);
token=flight.begin(selected);flight.clear();
assert.equal(flight.settle(token,proof),null);
assert.equal(flight.accept(proof),null);
console.log('PASS probe event/promise ordering, scope, stale operation and disposal checks');
