import {spawn} from 'node:child_process';
import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import path from 'node:path';
const output=path.resolve('output/p3/audio-transport');await mkdir(output,{recursive:true});
const root=await mkdtemp(path.join(output,'run-'));
const args=['test','-p','withu-server','audio_api::tests','--locked'];
const child=spawn('cargo',args,{env:{...process.env,CARGO_TARGET_DIR:path.resolve('output/p3/build-target')},stdio:['ignore','pipe','pipe']});
let log='';for(const stream of [child.stdout,child.stderr])stream.on('data',data=>{log+=data;process.stdout.write(data);});
const code=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve);});
await writeFile(path.join(root,'cargo-test.txt'),log);
await writeFile(path.join(root,'results.json'),JSON.stringify({success:code===0,command:['cargo',...args],scope:'real local HTTP audio transport with synthetic PCM/fictitious credential; not production session, cloud model or physical audio acceptance',productionSessionConnected:false,realKeysUsed:false,realCloudCallsMade:false,root},null,2));
console.log('Evidence '+root);process.exitCode=code===0?0:1;
