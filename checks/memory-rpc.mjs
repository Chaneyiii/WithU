import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {ClientServerOwner} from '../client/withu-window/index.mjs';
import {buildFixture,isolatedDirectory,seedFixture,inspectFixture,serverBinary} from './memory-fixture.mjs';

await buildFixture();
const root=await isolatedDirectory('memory-rpc');
const owners=[], checks=[];
const start=async()=>{const owner=new ClientServerOwner(serverBinary,{dataDir:root,test:true});owners.push(owner);await owner.start();return owner;};
const list=(owner,extra={},channel='list')=>owner.request('withu:memory:'+channel,{schema_version:1,scope:'comfort',retrieval:'list',query:null,limit:50,context_limit:6,...extra});
const correct=(owner,item,state,extra={})=>owner.request('withu:memory:correct',{schema_version:1,scope:'comfort',record:{...item.record,version:item.object_version+1,content:'我现在喜欢茉莉花茶。'},expected_object_version:item.object_version,expected_state_version:state,...extra});
const remove=(owner,item,state,extra={})=>owner.request('withu:memory:delete',{schema_version:1,scope:'comfort',target_type:'memory',target_id:item.record.id,expected_object_version:item.object_version,expected_state_version:state,sync_protection_token:randomUUID(),...extra});
try {
  let owner=await start();
  assert.deepEqual((await list(owner)).items,[]);
  await assert.rejects(list(owner,{scope:'private'}),/memory_scope/);
  await assert.rejects(list(owner,{retrieval:'exact',query:'  '}),/memory_query_required/);
  await assert.rejects(list(owner,{context_limit:13}),/memory_list_schema/);
  const semantic=await list(owner,{retrieval:'semantic',query:'喜欢什么'});
  assert.equal(semantic.retrieval.status,'no_results');
  assert.equal(semantic.retrieval.reason,'semantic_lexical_no_match');
  assert.deepEqual(semantic.items,[]);assert.deepEqual(semantic.context,[]);
  await owner.quit();
  await seedFixture(root);
  owner=await start();
  let response=await list(owner,{context_limit:1});
  assert.equal(response.items.length,3);assert.equal(response.context.length,1);
  assert.ok(response.items.every(item=>item.scope==='comfort'&&item.evidence.every(e=>e.scope==='comfort')));
  await assert.rejects(list(owner,{scope:'cowork:fixture'}),/memory_scope/);
  await assert.rejects(list(owner,{scope:'cowork:other'}),/memory_scope/);
  assert.equal((await list(owner,{context_limit:0},'context')).context.length,0);
  assert.equal((await list(owner,{retrieval:'exact',query:'无糖乌龙茶'})).items.length,2);
  assert.equal((await list(owner,{retrieval:'exact',query:'茉莉花茶'})).items.length,0);
  // T15: semantic retrieval actually runs over the derived lexical index;
  // hits carry canonical record ids and evidence, scope-bound.
  const semanticHit=await list(owner,{retrieval:'semantic',query:'乌龙茶 茶饮',context_limit:6});
  assert.equal(semanticHit.retrieval.status,'supported');
  assert.equal(semanticHit.retrieval.reason,'');
  assert.ok(semanticHit.context.some(row=>row.record.id==='fixture-memory-tea'),'semantic hit returns the tea memory');
  assert.ok(semanticHit.context.every(row=>row.record.id!=='fixture-memory-work'),'cowork memory never leaks into comfort semantic search');
  checks.push('real owner/server empty/list/exact/semantic hit + honest no_results, scope isolation and bounded context');
  let tea=response.items.find(item=>item.record.id==='fixture-memory-tea');
  assert.equal(tea.deletion_impact.count,5);
  for(const extra of [{expected_state_version:response.state_version-1},{expected_object_version:2}])
    await assert.rejects(correct(owner,tea,response.state_version,extra),/version_conflict/);
  await assert.rejects(correct(owner,tea,response.state_version,{scope:'cowork:fixture'}),/memory_scope/);
  for(const record of [{...tea.record,version:2,confirmed:false},{...tea.record,version:2,save_permission:false},{...tea.record,version:2,kind:'affect_hypothesis'},{...tea.record,version:2,access_token:'FICTIONAL-TOKEN'},{...tea.record,version:2,audio_base64:'AQABAA=='}])
    await assert.rejects(correct(owner,tea,response.state_version,{record}),/memory_correct_schema|memory_not_eligible/);
  const corrected=await correct(owner,tea,response.state_version);
  assert.equal(corrected.item.object_version,2);
  await assert.rejects(correct(owner,tea,response.state_version),/version_conflict/);
  response=await list(owner,{retrieval:'exact',query:'茉莉花茶'});
  assert.equal(response.items.length,1);tea=response.items[0];assert.equal(tea.evidence[0].version,1);
  assert.equal(tea.record.confirmed,true);assert.equal(tea.record.save_permission,true);
  checks.push('object/state CAS, scoped correction, original evidence, permission/affect/token/audio rejection');
  await owner.quit();owner=await start();
  response=await list(owner,{retrieval:'exact',query:'茉莉花茶'});assert.equal(response.items[0].object_version,2);
  tea=response.items[0];
  await assert.rejects(remove(owner,tea,response.state_version,{scope:'cowork:fixture'}),/memory_scope/);
  await assert.rejects(remove(owner,tea,response.state_version,{expected_state_version:0}),/version_conflict/);
  await assert.rejects(remove(owner,tea,response.state_version,{target_type:'evidence'}),/target_type_conflict/);
  const deleted=await remove(owner,tea,response.state_version);
  assert.equal(deleted.impact.count,5);assert.equal(deleted.tombstone.deleted_version,3);
  assert.deepEqual((await list(owner)).items.map(item=>item.record.id),['fixture-memory-walk']);
  const semanticAfterDelete=await list(owner,{retrieval:'semantic',query:'乌龙茶 茶饮'});
  assert.ok(semanticAfterDelete.context.every(row=>row.record.id!=='fixture-memory-tea'),'deleted memory never revives through the semantic index');
  await assert.rejects(correct(owner,tea,deleted.state_version),/deleted/);
  await assert.rejects(remove(owner,tea,deleted.state_version),/deleted/);
  await owner.quit();
  const snapshot=await inspectFixture(root);
  assert.equal(snapshot.tombstones.length,5);assert.equal(snapshot.derivatives.length,0);
  assert.equal(snapshot.tombstones.find(t=>t.target_id===tea.record.id).deleted_version,3);
  owner=await start();assert.equal((await list(owner)).items.length,1);
  await assert.rejects(list(owner,{scope:'cowork:fixture'}),/memory_scope/);
  await owner.request('withu:probe:crash',{}).catch(()=>{});await owner.exited;
  await assert.rejects(list(owner),/exited/);
  checks.push('restart, delete CAS/type errors, shared-evidence/transitive cascade, durable tombstone anti-resurrection, disconnect failure');
  await writeFile(path.join(root,'results.json'),JSON.stringify({success:true,fixture:true,realServer:true,checks,root},null,2));
  console.log(checks.map(check=>'PASS '+check).join('\n')+'\nEvidence '+root);
} finally {for(const owner of owners)await owner.forceStop();}
