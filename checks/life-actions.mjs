import assert from 'node:assert/strict';
import {lifeApprovalBlock,createLifeActionHandler} from '../client/withu-renderer/src/life-actions.js';
import {createActionIntent,createCancelIntent} from '../client/withu-renderer/src/intelligent-ui/action-adapter.js';
const prepared={operation_id:'one',plan:{goal:{description:'保存提醒'}},approval:{approval_id:'allow-one',expires_at:500,action:{action_id:'a',action_version:1,idempotency_key:'i',cancel_token:'c'}}};
const block=lifeApprovalBlock(prepared,'chat-a'),calls=[];
const bridge={async lifeDecide(p){calls.push(['decide',p]);},async lifeExecute(p){calls.push(['execute',p]);return {receipt:{status:'applied'}};},async lifeCancel(p){calls.push(['cancel',p]);}};
const handle=createLifeActionHandler({prepared,block,bridge});
assert.equal(calls.length,0);
await assert.rejects(handle({...createActionIntent(block,'click',100),conversation_id:'chat-b'}),/reference/);
await assert.rejects(handle(createActionIntent(block,'voice',100)),/explicit_allow/);
assert.equal(calls.length,0);
await handle(createActionIntent(block,'click',100));
assert.deepEqual(calls.map(x=>x[0]),['decide','execute']);
assert.equal(calls[0][1].explicit_user_allow,true);
await assert.rejects(handle(createActionIntent(block,'click',100)),/duplicate/);
await handle(createCancelIntent(block,100));
assert.equal(calls.at(-1)[0],'cancel');
console.log('PASS real life typed-intent host binding, explicit approval, duplicate and cancel');
