const {app,BrowserWindow}=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const root=process.env.WITHU_D3_GUI_ROOT;
if(!root)throw Error('isolated GUI fixture root required');
app.setPath('userData',path.join(root,'electron'));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
app.whenReady().then(async()=>{
  const win=new BrowserWindow({show:false,width:1440,height:1000,webPreferences:{contextIsolation:true,nodeIntegration:false,sandbox:true,offscreen:true,backgroundThrottling:false}});
  const capture=async()=>{win.webContents.invalidate();await delay(250);return (await win.webContents.capturePage()).toPNG();};
  const js=source=>win.webContents.executeJavaScript(source,true);
  const until=async source=>{for(let n=0;n<150;n++){if(await js(source))return;await delay(50);}throw Error('GUI wait: '+source);};
  const click=source=>js(`(${source}).click()`);
  const textSelector=text=>`[...document.querySelectorAll('.memory-manager button')].find(button=>button.textContent.trim()===${JSON.stringify(text)})`;
  const setValue=async(selector,value)=>js(`(()=>{const input=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(input.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)});input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  try {
    await win.loadURL('http://127.0.0.1:4177/#/settings/data-privacy');
    await until(`document.querySelectorAll('.memory-item').length===3`);
    assert.ok(await js(`document.querySelector('.preview-badge').textContent.includes('隔离 fixture')`));
    assert.ok(await js(`['memorySave','memoryList','memoryContext','memoryCorrect','memoryDelete'].every(method=>typeof window.withuPreview[method]==='function')`));
    await click(`document.querySelector('.memory-item')`);
    await until(`!!document.querySelector('.memory-detail textarea')`);
    assert.ok(await js(`document.querySelector('.memory-detail').textContent.includes('用户已确认保存') && document.querySelector('.memory-detail').textContent.includes('5 条')`));
    await fs.writeFile(path.join(root,'memory-manager.png'),await capture());
    await setValue('.memory-detail textarea','GUI 纠正：我喜欢茉莉花茶。');
    await click(textSelector('保存纠正'));
    await until(`document.querySelector('.memory-item-content')?.textContent.includes('GUI 纠正')`);
    await click(`document.querySelector('.memory-item')`);
    assert.ok(await js(`document.querySelector('.memory-detail small').textContent.includes('object v2')`));
    await click(textSelector('删除'));
    await until(`!!document.querySelector('.memory-confirm')`);
    assert.equal(await js(`document.querySelectorAll('.memory-item').length`),3,'no deletion before confirmation');
    await click(textSelector('取消'));
    assert.equal(await js(`document.querySelectorAll('.memory-item').length`),3);
    await click(textSelector('删除'));await click(textSelector('确认删除'));
    await until(`document.querySelectorAll('.memory-item').length===1`);
    await click(textSelector('语义'));
    await until(`!!document.querySelector('.memory-status')`);
    assert.equal(await js(`document.querySelectorAll('.memory-item').length`),0);
    assert.ok(await js(`document.querySelector('.memory-status').textContent.includes('暂不可用')`));
    await fs.writeFile(path.join(root,'memory-semantic-unavailable.png'),await capture());
    await click(textSelector('全部'));
    await until(`document.querySelectorAll('.memory-item').length===1`);
    assert.ok(await js(`document.querySelector('.memory-create button[type="submit"]').disabled && !document.querySelector('.memory-permission input').checked`));
    await setValue('.memory-create input:not([type="checkbox"])','GUI 明示保存');
    await setValue('.memory-create textarea','只保存此处由用户明确输入的事实。');
    assert.ok(await js(`document.querySelector('.memory-create button[type="submit"]').disabled`));
    await click(`document.querySelector('.memory-permission input')`);
    assert.equal(await js(`document.querySelector('.memory-create button[type="submit"]').disabled`),false);
    await setValue('.memory-create textarea','只保存此处由用户明确确认的事实。');
    assert.ok(await js(`!document.querySelector('.memory-permission input').checked && document.querySelector('.memory-create button[type="submit"]').disabled`),'editing requires renewed explicit confirmation');
    await click(`document.querySelector('.memory-permission input')`);
    await click(textSelector('确认保存记忆'));
    await until(`document.querySelectorAll('.memory-item').length===2 && !document.querySelector('.memory-permission input').checked`);
    await fs.writeFile(path.join(root,'memory-explicit-save.png'),await capture());

    await click(textSelector('全部'));
    await setValue('[aria-label="记忆作用域"]','cowork:fixture');
    await until(`!!document.querySelector('.memory-error')`);
    assert.ok(await js(`document.querySelector('.memory-error').textContent.includes('不可访问')`));
    assert.equal(await js(`document.querySelectorAll('.memory-item').length`),0);
    await setValue('[aria-label="记忆作用域"]','private');
    await until(`!!document.querySelector('.memory-error')`);
    assert.ok(await js(`document.querySelector('.memory-error').textContent.includes('不可访问')`));
    assert.equal(await js(`document.querySelectorAll('.memory-item').length`),0);
    await fs.writeFile(path.join(root,'memory-scope-error.png'),await capture());
    await js(`(async()=>{const {initialView}=await import('/src/store.js');const stored=(await window.withuPreview.viewGet({id:'client'})).object;const previous=stored||{...initialView,version:0};await window.withuPreview.viewUpdate({object:{...previous,language:'English',version:previous.version+1},expected_version:previous.version});})()`);
    await win.reload();
    await until(`document.querySelectorAll('.memory-item').length===2 && document.querySelector('.memory-context strong')?.textContent==='Bounded context'`);
    await click(`document.querySelector('.memory-item')`);
    assert.ok(await js(`document.querySelector('.memory-detail').textContent.includes('User confirmed saving')`));
    await click(textSelector('Delete'));
    await until(`document.querySelector('.memory-confirm')?.textContent.includes('Confirm deletion')`);
    await fs.writeFile(path.join(root,'memory-manager-english.png'),await capture());
    await click(textSelector('Cancel'));
    await setValue('[aria-label="Memory scope"]','private');
    await until(`document.querySelector('.memory-error')?.textContent.includes('This scope is not accessible')`);
    await fs.writeFile(path.join(root,'results.json'),JSON.stringify({success:true,fixture:true,checks:['actual mounted GUI with real preview owner/server','explicit save requires unchecked permission and renewed confirmation after edits','evidence/permission/recursive impact','CAS correction persisted in actual list','delete confirmation/cancel and real cascade','semantic unavailable','scope isolation and denied scope error','preview token/origin rejection']},null,2));
    console.log('PASS D3 isolated GUI: mount, real correction/delete, confirmation, evidence, scope, unavailable, English/Chinese and rejected preview access');
    win.destroy();app.exit(0);
  } catch(error) {console.error(error.stack);win.destroy();app.exit(1);}
});
